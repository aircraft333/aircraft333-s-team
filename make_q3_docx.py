h1("一、预报部分：三个模型（在问题二基础上各有一处升级）")

h2("1）光伏发电预报：附件3 点值插值 + 历史外推混合权重")
para("问题三与问题二最大的不同，是题目给出了附件3 的光伏发电功率预报（0:00、6:00、12:00、"
     "18:00 各发布一次，每次给出其后的逐整点预报）。因此光伏不再只能靠历史外推，而是多了"
     "一条独立的信息渠道。")
para("【口径标定】附件3 的“预报 k 小时”是发布后第 k 个整点时刻的瞬时点值，而不是该小时的"
     "平均功率。故需先把整点值线性插值到 10 分钟时段的右端点：")
eq(r"\hat{G}^{\mathrm{att3}}_{d,t} = \mathrm{interp}\!\left(\frac{t}{6},\ \{(h,\ G^{\mathrm{att3}}_{d,h})\}\right)")
para("若误按“小时平均功率”处理，全年 MAE 会从 191.7 kW 恶化到 361.6 kW，可见口径标定必须先做对。")
para("【误差互补】附件3 有预报模型自身的误差，但能反映当天真实的天气变化；历史外推（前 3 天"
     "滑动平均）曲线平滑，却看不到当天的突变。两者误差来源不同、近似不相关，加权混合可以"
     "相互抵消：")
eq(r"\hat{G}_{d,t} = m\cdot\hat{G}^{\mathrm{att3}}_{d,t} + (1-m)\cdot\frac{1}{3}\sum_{j=1}^{3}G^{\mathrm{real}}_{d-j,\,t}")
para("实测（全 365 天、0:00 发布、逐槽 MAE）：附件3 单用 191.7 kW；前 3 天均值 152.7 kW；"
     "取 m = 0.4 混合后降到 130.6 kW。")
para("注意 m 的最终取值是**按全年总费用**扫描选定的（0.2~0.6 是一个很平坦的平台，"
     "见 q3_光伏权重复检.txt），而不是按 MAE 最小。这两件事并不等价——")
para("附件3 的预报精度随发布时刻推后而明显改善（12:00 发布只需预报未来 12 小时），"
     "因此逐决策时刻的 MAE 最优权重分别是 0.4 / 0.6 / 0.8 / 0.0。但把它们放进全年模型，"
     "费用反而一律变贵（+3.8 万 ~ +6.0 万）：因为光伏预报误差进入费用函数是**不对称**的——"
     "低估光伏只是多买电（代价 π），高估光伏却会造成缺口、按 5π 紧急购电；而提高附件3 权重在 "
     "6:00 引入的恰好是**高估**，紧急购电费因此从 54.5 万涨到 63.0 万，超过了预报改善的收益。")
note("这正是「预报精度指标 ≠ 决策目标」的一个实例：MAE 对误差的两个方向一视同仁，"
     "费用函数却不是。故问题三保持全天统一的 m = 0.4，不按时刻拆分。")
para("另外，在 6:00 / 12:00 / 18:00 做决策时，当天已经过去的时段其实际光伏功率是已知的，"
     "直接填入实际值，不需要预报。")

h2("2）负载预报：上周同一天 + 当日自适应修正")
para("基础方法与问题二完全一致，即“同星期法”——人类生产与生活作息有极强的周期性，直接取"
     "上一周同一时刻的真实负载：")
eq(r"\hat{L}_{d,t} = L^{\mathrm{real}}_{d-7,\,t}")
para("问题三额外引入当日自适应修正。在 6:00 / 12:00 / 18:00 这些决策时刻，当天一部分时段"
     "已经过去，其实际负载是已知的——这是不需要任何额外预报的免费信息。取已发生时段的"
     "“实际/预报”均值之比 k：")
eq(r"k_d = \mathrm{clip}\!\left(\frac{\mathrm{mean}(L_{d,\,1..t_0})}"
   r"{\mathrm{mean}(\hat{L}_{d,\,1..t_0})},\ 1-\lambda,\ 1+\lambda\right),\qquad \lambda = 0.2")
para("再用 k 缩放剩余时段的预报（限幅 ±20%，全年只有 2~3 天真正触发限幅）：")
eq(r"\hat{L}'_{d,t} = k_d\cdot\hat{L}_{d,t}\qquad (t > t_0)")
para("实测：|k − 1| 的全年均值只有 1.7%（约 78 kW），却把剩余时段的 MAE 从 198.4 kW 降到 "
     "172.9 kW（−12.9%）。这说明同星期法的误差里约有 13% 是“当天整体偏高/偏低”的公共偏移，"
     "乘一个系数就能整体去掉。")

h2("3）报童模型（安全裕量）：问题三与问题二的关键区别")
para("少买电的惩罚（5π）远大于多买电的成本（π），故用运筹学的报童模型设定风险裕量。"
     "设超额边际成本为 c_o（Over-order Cost），欠额边际损失为 c_u（Under-order Cost）：")
para("【计划阶段（0:00）】多买 1 kWh 的成本是 π_t，少买 1 kWh 则要按 5π_t 紧急购电：", indent=False)
eq(r"c_o = \pi_t,\qquad c_u = 5\pi_t - \pi_t = 4\pi_t"
   r"\quad\Longrightarrow\quad \alpha^{*} = \frac{c_u}{c_u + c_o} = \frac{4}{5} = 0.80")
para("【调整阶段（6:00 / 12:00 / 18:00）】问题三的调整电价规则改变了两侧的边际成本："
     "超出计划的部分单价为 1.5π_t，少买的部分只退 0.5π_t。因此：", indent=False)
eq(r"c_o = 1.5\pi_t,\qquad c_u = 5\pi_t - 1.5\pi_t = 3.5\pi_t"
   r"\quad\Longrightarrow\quad \alpha^{*} = \frac{c_u}{c_u + c_o} = \frac{3.5}{5} = 0.70")
para("两个阶段的临界分位并不相同（0.80 与 0.70），而两阶段共用同一个裕量，故最优裕量应落在 "
     "[0.70, 0.80] 区间内，取中点 α* = 0.75。")
note("这是先验预测，不是事后挑的。全年 334 天实测的分位曲线：q=0.70 → 13,624,983 元；"
     "q=0.75 → 13,589,362 元（最优）；q=0.80 → 13,598,165 元；q=0.85 → 13,668,602 元；"
     "q=0.90 → 13,853,989 元。最优点恰好落在预测区间的中点，说明成本结构建模是正确的。")
para("历史误差样本取的是“负载预报误差”。（问题二的裕量建在净负荷误差上，因为问题二的光伏"
     "也只有外推；问题三的光伏已由附件3 这条渠道承担，故裕量只加在负载侧，不重复计入。）")
eq(r"\varepsilon_{j,t} = L^{\mathrm{real}}_{j,t} - \hat{L}_{j,t}")
para("从过去 W 天的误差样本中取 α* 分位数，即为该时段的裕量 X（回看窗口 W = 60 天，"
     "且严格只用当日之前的数据）：")
eq(r"X_{d,t} = \mathrm{Quantile}_{\alpha^{*}}\!\left(\left\{\varepsilon_{j,t}\ \middle|\ "
   r"\max(0,\,d-W) \le j < d\right\}\right)")
para("X_{d,t} 即为裕量。最终等效预测负荷：")
eq(r"\tilde{L}_{d,t} = \hat{L}_{d,t} + X_{d,t}")

h1("二、计划部分：0:00 日前单日线性规划（与问题二同构）")
para("决策变量：b_t（购电量）、c_t（充电功率）、d_t（放电功率）、s_t（弃光功率）、"
     "E_t（时段末储电量）。")
para("约束条件：", indent=False)
item("日前功率平衡约束：", "1.")
eq(r"b_t + \hat{G}_{d,t} + d_t - c_t - s_t = \tilde{L}_{d,t},\qquad \forall t = 1,\dots,144")
item("储能动态容量演化与初值约束：", "2.")
eq(r"E_t = E_{t-1} + \left(\eta c_t - \frac{d_t}{\eta}\right)\Delta t,"
   r"\qquad E_0 = E_d^{\mathrm{start}}")
item("储能运行上下限约束：", "3.")
eq(r"0 \le c_t \le P_{\max},\qquad 0 \le d_t \le P_{\max}\qquad (P_{\max} = 5000\ \mathrm{kW})")
eq(r"E_{\min} \le E_t \le E_{\max}\qquad (E_{\min} = 1200,\ E_{\max} = 10800\ \mathrm{kWh})")
item("非负性：b_t ≥ 0，s_t ≥ 0。", "4.")
note("无 0-1 变量的松弛性证明：因为同时充放电会带来 2(1 − η) 的净能量损耗，在线性规划求"
     "极小值时，最优解天然满足互斥条件 c_t·d_t = 0，因此可以直接用连续变量 LP 求解，"
     "无需引入 0-1 变量，计算更快。")
para("目标函数：最小化单日计划购电费用：", indent=False)
eq(r"\min\ \sum_{t=1}^{144}\pi_t\cdot b_t\cdot\Delta t")

h1("三、调整部分：6:00 / 12:00 / 18:00 多阶段滚动调整（本问核心）")
para("【购电费用函数】设 0:00 计划购电量为 b^p_t、最终调整后购电量为 b^a_t，题目给出的"
     "单时段费用规则为：")
eq(r"C_t = \pi_t\min(b^{p}_t,\ b^{a}_t) + 0.5\pi_t\left(b^{p}_t - b^{a}_t\right)^{+}"
   r" + 1.5\pi_t\left(b^{a}_t - b^{p}_t\right)^{+}")
para("即：不超过计划的部分按 π_t 计费；少买（计划高于最终）的违约部分按 0.5π_t 计费；"
     "多买（最终高于计划）的超调部分按 1.5π_t 计费。")
para("【分段线性化】该函数关于 b^a_t 是凸的分段线性函数，引入 δ⁺、δ⁻ ≥ 0 即可用纯 LP "
     "精确表达：")
eq(r"b^{a}_t = b^{p}_t + \delta^{+}_t - \delta^{-}_t"
   r"\quad\Longrightarrow\quad C_t = \pi_t b^{p}_t + 1.5\pi_t\,\delta^{+}_t - 0.5\pi_t\,\delta^{-}_t")
para("由于目标是最小化 C_t，最优解不会让 δ⁺ 与 δ⁻ 同时取正，故该线性化是精确的。")
para("【逐槽规则在 LP 中的精确嵌入】问题二已经确认：购电量一旦锁定，储能在每个时段只能做"
     "“被动平衡”：")
eq(r"\Delta_t = L_t - G_t - b^{a}_t")
para("该规则看似含 min/max，实则是凸分段线性的，可用纯 LP 精确表达（功率平衡 + 四个上界"
     "约束）：")
eq(r"d_t - c_t - s_t - e_t = L_t - G_t - b^{a}_t")
eq(r"\begin{aligned}"
   r"d_t &\le P_{\max}, \qquad d_t \le (E_{t-1}-E_{\min})\,\eta/\Delta t\\"
   r"c_t &\le P_{\max}, \qquad c_t \le (E_{\max}-E_{t-1})/(\eta\,\Delta t)\\"
   r"s_t &\le G_t, \qquad e_t \ge 0, \qquad s_t \ge 0"
   r"\end{aligned}")
para("【为什么 LP 的解就等于逐槽规则】目标中 e_t 的系数 5π_t > 0，会迫使 d_t 顶到上界，"
     "恰好是 min(Δ_t, 上界)；再给 s_t 一个极小的系数 ε = 1e-6（仅为打破简并，不改变最优值），"
     "迫使 c_t 顶到上界，恰好是 min(−Δ_t, 上界)。于是 LP 的最优解与实际执行的逐槽规则"
     "逐点一致，分段滚动不会出现前后矛盾。")
para("【滚动逻辑】t_0 时刻只优化 t ∈ [t_0, 144) 的购电量；[0, t_0) 的时段已经发生、取值锁定，"
     "其费用是常数、不影响 arg min，可以直接从目标中剔除。进入 t_0 时的储电量由“实际数据 + "
     "已锁定购电量”仿真得到，是已知量。又因为逐槽规则不含前瞻，全天仿真与分段仿真拼接完全"
     "等价，因此多阶段滚动是自洽的。")
para("目标函数：", indent=False)
eq(r"\min\ \sum_{t=t_0}^{144}\left[\,C_t + 5\pi_t\, e_t\,\Delta t\,\right]")

h1("四、紧急购电与实际执行：逐槽法（与问题二完全相同）")
para("进入时段 t，实际负荷与实际光伏功率出现，会与预测值产生实时净偏差：")
eq(r"\Delta P_t = L^{\mathrm{real}}_t - G^{\mathrm{real}}_t - b^{a}_t")
para("ΔP_t > 0，存在电力缺口：先用先前储存的电量放电，放电过程受到最大放电功率 P_max 与"
     "当前剩余可用电量 (E_{t−1} − E_min) 的双重约束：")
eq(r"d_t = \min\!\left(\Delta P_t,\ P_{\max},\ \frac{(E_{t-1}-E_{\min})\,\eta}{\Delta t}\right)")
para("如果储存电量不足以弥补电力缺口，则触发紧急购电：")
eq(r"e_t = \Delta P_t - d_t")
para("ΔP_t < 0，电力过剩：把富余的电能充进储能电池储存起来，留给以后缺电时使用。所充电功率：")
eq(r"c_t = \min\!\left(-\Delta P_t,\ P_{\max},\ \frac{E_{\max}-E_{t-1}}{\eta\,\Delta t}\right)")
para("如果已经超过电池储能上限，则进行无损耗弃电。弃电功率：")
eq(r"s_t = -\Delta P_t - c_t")
para("逐槽状态变化：")
eq(r"E_t = E_{t-1} + \left(\eta c_t - \frac{d_t}{\eta}\right)\Delta t")
para("更新后的 E_t 作为下一个时段 t+1 的初始状态，依次推进至当日最后一个时段"
     "（144 个 10 分钟时段）。")

